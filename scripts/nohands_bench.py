"""Benchmark NoHands against baselines on synthetic sessions with exact ground truth.

    python scripts/nohands_bench.py

Writes eval/synthetic.md and eval/synthetic.json. Methods, all given the same masks except the
temporal median, which has none:
  - NoHands: clean plate + transient veto (the shipped pipeline)
  - NoHands without veto: every recorded change replayed, none vetoed
  - masked median per 5 s segment (Loomis Painter style)
  - temporal median over 5 s (no masks)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import numpy as np

from nohands.cleanplate import CleanPlate, CleanPlateConfig, first_visible_canvas
from nohands.config import ROOT
from nohands.evaluate import frame_report, masked_median, temporal_median
from nohands.occluders import occluders, painted
from tests.synthetic import SKIN, painted_hand_session, resting_hand_session, synthetic_session

FPS = 2.0
SEGMENT = 10  # frames: 5 s at 2 fps
DILATE = 6
PERSIST = 4  # frames: 2 s at 2 fps


def nohands(frames, masks, *, veto: bool) -> list[np.ndarray]:
    start = first_visible_canvas(iter(frames), iter(masks), dilate_px=DILATE, steady_frames=PERSIST)
    plate = CleanPlate(start, CleanPlateConfig(dilate_px=DILATE, persist_frames=PERSIST, record=True))
    for frame, mask in zip(frames, masks):
        plate.update(frame, mask)
    timeline = plate.timeline()
    if veto:
        timeline = timeline.without(timeline.transients(threshold=20, window=round(300 * FPS)))
    return [canvas.copy() for canvas, _ in timeline.replay(start, len(frames))]


def scenarios() -> dict[str, tuple[list, list, list, np.ndarray | None]]:
    moving = synthetic_session(frames=90)
    resting = resting_hand_session(frames=90, rest=(20, 60))
    painted_session, canvas = painted_hand_session(frames=90)
    objects = {index: found for index, (_, found, _) in enumerate(painted_session)}
    painted_masks = occluders(objects, painted(objects, canvas, FPS), canvas.shape)
    painted_area = (painted_session[-1][2] == SKIN).all(axis=2)
    return {
        "moving hand + shadow": ([f for f, _, _ in moving], [m for _, m, _ in moving], [t for _, _, t in moving], None),
        "resting hand + static shadow": (
            [f for f, _, _, _ in resting], [m for _, m, _, _ in resting], [t for _, _, t, _ in resting], None,
        ),
        "painted hand on canvas": (
            [f for f, _, _ in painted_session],
            [painted_masks.get(index) for index in range(len(painted_session))],
            [t for _, _, t in painted_session],
            painted_area,
        ),
    }


def main() -> None:
    rows = []
    for name, (frames, masks, truths, painted_area) in scenarios().items():
        methods = {
            "NoHands": nohands(frames, masks, veto=True),
            "NoHands without veto": nohands(frames, masks, veto=False),
            "masked median (Loomis-style)": list(masked_median(frames, masks, SEGMENT, DILATE)),
            "temporal median (no masks)": list(temporal_median(frames, SEGMENT)),
        }
        for method, outputs in methods.items():
            rows.append({"scenario": name, "method": method,
                         **frame_report(outputs, truths, skin=SKIN, painted=painted_area)})
            print(f"{name:30} {method:30} {rows[-1]}")

    out = ROOT / "eval"
    out.mkdir(exist_ok=True)
    (out / "synthetic.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    lines = [
        "# Synthetic benchmark",
        "",
        "Exact ground truth for every frame; lower is better everywhere. Generated by `scripts/nohands_bench.py`.",
        "",
        "These scenes were written alongside the method, so they show it does what it was designed to do:",
        "a sanity check, not a stand-in for real footage.",
        "",
        "- **Mean / final ΔE00**: colour difference from the true canvas (CIEDE2000). It includes delay: paint",
        "  shown late, because the hand was still over it, counts as error here.",
        "- **Artifact frames / pixels**: output that matches *no* real state of the canvas from the last 10 s",
        "  (a shadow, part of the painter, a smear). Delay doesn't count.",
        "- **Painter visible**: artifact pixels that look like skin, outside anything actually painted.",
        "",
        "| Scenario | Method | Mean ΔE00 | Final ΔE00 | Artifact frames % | Artifact pixels % | Painter visible frames % |",
        "|---|---|---|---|---|---|---|",
    ]
    lines += [
        f"| {r['scenario']} | {r['method']} | {r['mean_delta_e']} | {r['final_delta_e']} | "
        f"{r['artifact_frames_pct']} | {r['artifact_pixels_pct']} | {r['painter_visible_frames_pct']} |"
        for r in rows
    ]
    (out / "synthetic.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out / 'synthetic.md'}")


if __name__ == "__main__":
    main()
